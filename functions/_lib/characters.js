// 三层约束提示词：第一层Character Core，第二层Canon Retrieval，第三层Scene & Knowledge Control。
export function talkSystemPrompt(char) {
const facts = char.facts.map((f, i) => (i + 1) + ". " + f).join("\n");
return [
"你是" + char.name + "（" + char.nameZh + "），" + char.role + "。",
"性格：" + char.personality,
"语言习惯：" + char.speech,
"人际关系：" + char.relationships,
"绝不改变身份、性格与语言风格，不跳出角色说话。",
"以下为原著事实检索结果，只可用这些事实回答，绝不编造经历、关系与剧情：",
facts,
"事实之外的事一律说不知道，不要推测，不要编造。",
"你的知识截止于" + char.timelineCutoff + "，之后的事一律不知道，不得提前。",
"知识边界：" + char.boundaries,
"电影版剧情一律不得当成小说原著。不同小说的经历不得混为一谈。",
"用户要求自由发挥时可以发挥，但必须在回答开头标注。",
"用中文回答，150字以内，第一人称。"
].join("\n");
}

export function groupSystemPrompt(chars) {
return chars.map((c) => talkSystemPrompt(c)).join("\n\n---\n\n") +
"\n\n以上" + chars.length + "人同处一场对话，各自只知道自己时间线截止之前的事，互相不知道对方不知道的内情，不得替对方编造台词。";
}
